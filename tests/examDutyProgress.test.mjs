import { strict as assert } from 'node:assert';
import { dutyProgress, dhakaClock, exchangeConflictText, proxyConflictText } from '../src/utils/examDutyUpcoming.js';
const day={date:'2026-10-25',startTime:'10:00 AM',endTime:'11:30 AM',assignment:'official'};
const at=(h,m=0)=>({date:'2026-10-25',minutes:h*60+m});
assert.equal(dutyProgress(day,at(10,13)),'remaining','current exam remains visible');
assert.equal(dutyProgress(day,at(11,29)),'remaining','during duty remains visible');
assert.equal(dutyProgress(day,at(11,30)),'completed','completed at end time');
assert.equal(dutyProgress(day,at(15)),'completed','morning exam moves to completed by afternoon');
assert.equal(dutyProgress(day,{date:'2026-10-24',minutes:1439}),'remaining');
assert.equal(dutyProgress(day,{date:'2026-10-26',minutes:0}),'completed');
assert.equal(dutyProgress({...day,assignment:'proxy'},at(10,13)),'remaining');
assert.equal(dutyProgress({...day,assignment:'exchange'},at(10,13)),'remaining');
assert.equal(dutyProgress({...day,assignment:'transferred_out'},at(10,13)),'reassigned');
assert.equal(dutyProgress({...day,changeSide:'outgoing'},at(10,13)),'reassigned');
assert.equal(dutyProgress({...day,endTime:''},at(15)),'remaining','missing OCR end time should not disappear');
assert.equal(dhakaClock(new Date('2026-10-25T04:13:00Z')).minutes,613);
assert.equal(proxyConflictText(1),'You already have a duty at this time.');
assert.equal(proxyConflictText(3),'You already have 3 duties at this time.');
assert.equal(exchangeConflictText(1,0,'JFM'),"You already have a duty at the time of JFM's selected duty.");
assert.equal(exchangeConflictText(0,1,'JFM'),'JFM already has a duty at the time of your selected duty.');
assert.equal(exchangeConflictText(1,1,'JFM'),"You already have a duty at the time of JFM's selected duty. JFM already has a duty at the time of your selected duty.");
assert.equal(exchangeConflictText(0,0,'JFM'),'');
console.log('PASS: progress filtering, timezone, transfer history and clear overlap warnings.');
